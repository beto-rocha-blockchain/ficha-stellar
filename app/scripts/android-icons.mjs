// Builds the Android launcher icon and splash from ../brand (run by `npm run android:icons`,
// which `npm run android:sync` calls). Re-run it whenever the brand files change.
//
// - Adaptive icon (Android 8+): the paths of brand/ficha-app-icon.svg become a
//   VectorDrawable foreground (the SVG keeps the mark inside the 313/1024 safe
//   circle, which maps 1:1 onto the 108 dp adaptive canvas); its background
//   rect becomes @color/ic_launcher_background.
// - Legacy icons (Android 6-7): brand/png/ficha-app-icon-512x512.png, downscaled
//   (area average) to each density; the round variant is masked to a circle.
// - Splash: brand background colour with the launcher icon in the middle.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const brand = join(app, "..", "brand");
const res = join(app, "android", "app", "src", "main", "res");
if (!existsSync(res)) {
  console.error("[android-icons] android/ not found: run `npx cap add android` first");
  process.exit(1);
}

const svg = readFileSync(join(brand, "ficha-app-icon.svg"), "utf8");
const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];

// --- adaptive foreground (VectorDrawable) --------------------------------
const gradients = {};
for (const m of svg.matchAll(/<linearGradient\b([^>]*)>([\s\S]*?)<\/linearGradient>/g)) {
  const stops = [...m[2].matchAll(/<stop\b[^>]*>/g)].map((s) => ({
    offset: attr(s[0], "offset") ?? "0",
    color: attr(s[0], "stop-color") ?? "#000000",
  }));
  gradients[attr(m[1], "id")] = {
    x1: attr(m[1], "x1"), y1: attr(m[1], "y1"), x2: attr(m[1], "x2"), y2: attr(m[1], "y2"), stops,
  };
}
const bg = attr(/<rect\b[^>]*>/.exec(svg)?.[0] ?? "", "fill") ?? "#070D1A";
const viewBox = (attr(/<svg\b[^>]*>/.exec(svg)[0], "viewBox") ?? "0 0 1024 1024").split(/\s+/);

const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(({ 0: tag }) => {
  const fill = attr(tag, "fill") ?? "#000000";
  const rule = attr(tag, "fill-rule") === "evenodd" ? "evenOdd" : "nonZero";
  const d = attr(tag, "d");
  const ref = /^url\(#(.+)\)$/.exec(fill)?.[1];
  if (!ref) return `  <path android:fillColor="${fill}" android:fillType="${rule}" android:pathData="${d}"/>`;
  const g = gradients[ref];
  const items = g.stops.map((s) => `        <item android:offset="${s.offset}" android:color="${s.color}"/>`).join("\n");
  return `  <path android:fillType="${rule}" android:pathData="${d}">
    <aapt:attr name="android:fillColor">
      <gradient android:type="linear" android:startX="${g.x1}" android:startY="${g.y1}" android:endX="${g.x2}" android:endY="${g.y2}">
${items}
      </gradient>
    </aapt:attr>
  </path>`;
});

const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs from brand/ficha-app-icon.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="${viewBox[2]}" android:viewportHeight="${viewBox[3]}">
${paths.join("\n")}
</vector>
`;
mkdirSync(join(res, "drawable-v24"), { recursive: true });
writeFileSync(join(res, "drawable-v24", "ic_launcher_foreground.xml"), vector);
rmSync(join(res, "drawable", "ic_launcher_background.xml"), { force: true });

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`;
writeFileSync(join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), adaptive);
writeFileSync(join(res, "mipmap-anydpi-v26", "ic_launcher_round.xml"), adaptive);
writeFileSync(
  join(res, "values", "ic_launcher_background.xml"),
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${bg}</color>\n</resources>\n`,
);

// --- legacy PNG icons ------------------------------------------------------
const src = PNG.sync.read(readFileSync(join(brand, "png", "ficha-app-icon-512x512.png")));

function resize(img, size, round) {
  const out = new PNG({ width: size, height: size });
  const k = img.width / size;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const acc = [0, 0, 0, 0];
      let n = 0;
      for (let sy = Math.floor(y * k); sy < Math.min(img.height, Math.ceil((y + 1) * k)); sy++) {
        for (let sx = Math.floor(x * k); sx < Math.min(img.width, Math.ceil((x + 1) * k)); sx++) {
          const i = (sy * img.width + sx) * 4;
          for (let c = 0; c < 4; c++) acc[c] += img.data[i + c];
          n++;
        }
      }
      const o = (y * size + x) * 4;
      for (let c = 0; c < 4; c++) out.data[o + c] = Math.round(acc[c] / n);
      if (round) {
        // 1 px anti-aliased circular mask
        const r = size / 2;
        const dist = Math.hypot(x + 0.5 - r, y + 0.5 - r);
        out.data[o + 3] = Math.round(out.data[o + 3] * Math.max(0, Math.min(1, r - dist + 0.5)));
      }
    }
  }
  return PNG.sync.write(out);
}

const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [dpi, size] of Object.entries(densities)) {
  const dir = join(res, `mipmap-${dpi}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "ic_launcher.png"), resize(src, size, false));
  writeFileSync(join(dir, "ic_launcher_round.png"), resize(src, size, true));
  rmSync(join(dir, "ic_launcher_foreground.png"), { force: true });
}

// --- splash ----------------------------------------------------------------
for (const d of readdirSync(res)) {
  if (!d.startsWith("drawable")) continue;
  rmSync(join(res, d, "splash.png"), { force: true });
  if (d !== "drawable" && readdirSync(join(res, d)).length === 0) rmSync(join(res, d), { recursive: true });
}
writeFileSync(
  join(res, "drawable", "splash.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-icons.mjs. Brand background with the launcher icon. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/ic_launcher_background"/>
    <item android:gravity="center" android:width="144dp" android:height="144dp" android:drawable="@mipmap/ic_launcher"/>
</layer-list>
`,
);

console.log(`[android-icons] adaptive (${paths.length} paths, bg ${bg}) + legacy PNGs + splash`);
